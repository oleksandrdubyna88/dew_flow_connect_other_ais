#!/bin/sh
# Free probe run INSIDE the sandbox/unit. Args: $1=row root. Prints one line per probe: ID result. Never prints file contents.
R=$1; RH=${2:?the real home path}; W=$R/cr/wt
t() { id=$1; shift; if out=$("$@" 2>&1); then echo "$id OK"; else echo "$id FAIL $(echo "$out" | head -1 | cut -c1-110)"; fi; }
t B1_wt_write sh -c "echo EDITED > $W/probe_a.txt"
t B2_main_new_file sh -c "echo X > $R/main/probe_new.txt"
t B2_main_edit_existing sh -c "echo X >> $R/main/canary.txt"
t B3_beside_new sh -c "echo X > $R/cr/probe_beside.txt"
t B3_beside_existing sh -c "echo X >> $R/cr/beside_canary.txt"
t B3_other_job sh -c "echo X >> $R/cr/other/other_canary.txt"
t B4_wt_git_pointer sh -c "echo X >> $W/.git"
t B4_main_git_write sh -c "echo X > $R/main/.git/probe_x"
t B4_main_git_hooks sh -c "echo X > $R/main/.git/hooks/pre-commit"
t B4_main_git_worktree_admin sh -c "echo X >> $R/main/.git/worktrees/wt/HEAD"
t B5_real_home_write sh -c "echo X > $RH/coai_e3s4_b5_canary.txt"
t B5_job_home_write sh -c "echo X > $R/c/home/probe_home.txt"
t B6_read_main_secret sh -c "cat $R/main/secret_d.txt >/dev/null"
t B6_read_other_job sh -c "cat $R/cr/other/other_canary.txt >/dev/null"
t B7_list_main sh -c "ls $R/main >/dev/null"
t B7_find_main sh -c "find $R/main -maxdepth 1 -name secret_d.txt | grep -q secret"
t B7_list_real_home sh -c "ls $RH >/dev/null"
t B11_real_codex_auth_exists sh -c "test -e $RH/.codex/auth.json"
t B11_job_codex_auth_read sh -c "head -c 1 $R/c/home/.codex/auth.json >/dev/null"
t B11_job_agy_token_read sh -c "head -c 1 $R/c/home/.gemini/antigravity-cli/antigravity-oauth-token >/dev/null"
t B11_parent_environ_read sh -c "cat /proc/$PPID/environ >/dev/null"
t B11_canary_env_in_own_env sh -c "env | grep -q '^COAI_CANARY_ENV='"
t B11_any_proc_environ_with_canary sh -c "grep -l COAI_CANARY_ENV /proc/[0-9]*/environ 2>/dev/null | grep -qv \"^/proc/self/\""
t B9_user_manager sh -c "systemd-run --user --quiet true"
t B9_dbus_socket sh -c "test -S /run/user/$(id -u)/bus"
t B9_wsl_interop sh -c "test -e /run/WSL || test -e /proc/sys/fs/binfmt_misc/WSLInterop"
t B9_windows_exe sh -c "ls /mnt/c/Windows/System32/cmd.exe"
t B9_mnt_c_listed sh -c "test -d /mnt/c"
t B10_net_example sh -c "curl -sS -m 6 -o /dev/null https://example.com"
t B10_net_dns sh -c "getent hosts example.com"
t B10_net_vendor_chatgpt sh -c "curl -sS -m 6 -o /dev/null https://chatgpt.com/"
t B10_net_ip sh -c "curl -sS -m 6 -o /dev/null https://1.1.1.1/"
t B8_symlink_file_out sh -c "ln -s $R/main/canary.txt $W/link_f && echo X >> $W/link_f"
t B8_symlink_dir_out sh -c "ln -s $R/main $W/link_d && echo X > $W/link_d/via_link.txt"
