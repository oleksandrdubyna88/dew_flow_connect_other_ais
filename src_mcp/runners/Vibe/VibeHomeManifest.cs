using System.Text.Json;
using System.Text.Json.Serialization;

namespace CoaiMcp.Runners.Vibe;

/// <summary>One file Vibe writes into an empty home whose bytes are pinned: its home-relative path and its SHA-256.</summary>
public sealed record VibePinnedFile(string Path, string Sha256);

/// <summary>What one Vibe version writes into an empty coai-owned home — the plugin files it unpacks, by hash.</summary>
public sealed record VibeHomeEntry(string Version, IReadOnlyList<VibePinnedFile> Pinned)
{
    /// <summary>The pinned file at <paramref name="path"/> (forward slashes, ordinal), or none.</summary>
    public IReadOnlyList<VibePinnedFile> At(string path) => [.. Pinned.Where(file => file.Path == path)];
}

/// <summary>
/// <c>shared/vibe-home-manifest.json</c>, embedded: what a coai-owned <c>VIBE_HOME</c> may hold (D17 of
/// <c>todo/PLAN_vibe_and_kimi_runtimes.md</c>; the run that wrote it is §24 of research/RESULTS_vibe_confinement.md).
/// </summary>
/// <remarks>
/// <para>Generated by <c>node scripts/vibe-home-manifest.mjs --write</c>, which starts Vibe on an empty home in the built
/// environment and hashes what it wrote. Three facts: the folder whose files are PINNED by hash (Vibe's bundled plugin
/// artifacts — "any file under <c>logs/session/plugins/</c>" would admit whatever a tampered or upgraded Vibe put there),
/// the paths admitted by NAME because their bytes are Vibe's caches, logs and sessions, and one entry per Vibe version
/// that was qualified. A version with no entry is RUN with a warning (the owner's decision of 2026-10-13: warn, not refuse) —
/// its plugin files admitted by name, the home's shape still checked; a measured version's mismatched bytes are refused.</para>
/// <para>Embedded for the reason every shared seed here is: a Native-AOT binary runs where no <c>shared/</c> exists, and a
/// launch must not be admitted against a manifest it could not read — a load failure is a refusal of every Vibe launch,
/// never an empty manifest that admits nothing and says so badly.</para>
/// </remarks>
public sealed record VibeHomeManifest(string PinnedPrefix, IReadOnlyList<string> Varying, IReadOnlyList<VibeHomeEntry> Versions)
{
    private const string Resource = "CoaiMcp.Runners.vibe-home-manifest.json";

    /// <summary>The manifest this build was shipped with, or the sentence that says why it cannot be read.</summary>
    public static VibeManifestLoad Builtin { get; } = Load();

    /// <summary>The entry for exactly <paramref name="version"/>, or none.</summary>
    public IReadOnlyList<VibeHomeEntry> For(string version) => [.. Versions.Where(entry => entry.Version == version)];

    /// <summary>The versions this manifest qualifies, for a refusal that must name them.</summary>
    public string Known => string.Join(", ", Versions.Select(entry => entry.Version));

    /// <summary>A manifest document, validated — or a refusal naming what is wrong with it.</summary>
    public static VibeManifestLoad Parse(string json)
    {
        try
        {
            return Validated(JsonSerializer.Deserialize(json, VibeHomeManifestJson.Default.ManifestFile));
        }
        catch (JsonException e)
        {
            return new VibeManifestLoad.Broken($"shared/vibe-home-manifest.json is not JSON: {e.Message}");
        }
    }

    private static VibeManifestLoad Validated(ManifestFile? file) =>
        file is { PinnedPrefix: { Length: > 0 } prefix, Varying.Count: > 0, Versions.Count: > 0 }
        && file.Versions.All(Complete)
            ? new VibeManifestLoad.Loaded(new VibeHomeManifest(prefix, [.. file.Varying], [.. file.Versions.Select(Entry)]))
            : new VibeManifestLoad.Broken("shared/vibe-home-manifest.json lacks its pinned prefix, its varying names or a complete version entry");

    private static bool Complete(ManifestVersion? version) =>
        version is { Version.Length: > 0, Pinned: not null }
        && version.Pinned.All(file => file is { Path.Length: > 0, Sha256.Length: 64 });

    private static VibeHomeEntry Entry(ManifestVersion? version) =>
        new(version!.Version!, [.. version.Pinned!.Select(file => new VibePinnedFile(file!.Path!, file.Sha256!.ToLowerInvariant()))]);

    private static VibeManifestLoad Load()
    {
        using var stream = typeof(VibeHomeManifest).Assembly.GetManifestResourceStream(Resource);
        if (stream is null)
        {
            return new VibeManifestLoad.Broken($"the embedded resource {Resource} is missing — this build cannot check a Vibe home");
        }

        using var reader = new StreamReader(stream);

        return Parse(reader.ReadToEnd());
    }
}

/// <summary>The manifest, or why there is none — a value, never an exception on the launch path.</summary>
public abstract record VibeManifestLoad
{
    private VibeManifestLoad()
    {
    }

    public sealed record Loaded(VibeHomeManifest Manifest) : VibeManifestLoad;

    public sealed record Broken(string Reason) : VibeManifestLoad;
}

/// <summary>The file as JSON spells it. Every field nullable: an omitted one arrives null (doctrine 4a).</summary>
internal sealed record ManifestFile
{
    public string? PinnedPrefix { get; init; }

    public IReadOnlyList<string>? Varying { get; init; }

    public IReadOnlyList<ManifestVersion?>? Versions { get; init; }
}

internal sealed record ManifestVersion
{
    public string? Version { get; init; }

    public IReadOnlyList<ManifestPinned?>? Pinned { get; init; }
}

internal sealed record ManifestPinned
{
    public string? Path { get; init; }

    public string? Sha256 { get; init; }
}

/// <summary>Source-generated, so the Native-AOT binary reads the manifest without reflection.</summary>
[JsonSourceGenerationOptions(PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase)]
[JsonSerializable(typeof(ManifestFile))]
internal sealed partial class VibeHomeManifestJson : JsonSerializerContext;
