// Regenerates src/helpPrompts.ts from the prompts the SERVER ships.
//
// helpPrompts.ts has said "regenerate this file" since it was written, and there was nothing to
// regenerate it with — so the copy was maintained by hand, one entry at a time, against a test
// that demands byte equality. That works for three prompts and stops working at twenty-five.
//
// The grouping is READ from src/prompts.ts rather than repeated here: that file is already the
// panel's mirror of the server catalog, so taking the order from it means a lens added in one
// place cannot end up ordered differently in the other. The only thing this script decides is
// that the conventions pass stands alone, because it belongs to all three code roles at once.
//
//   node scripts/generate-help-prompts.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const promptsDir = join(here, '..', '..', 'src_mcp', 'src', 'prompts');
const out = join(here, '..', 'src', 'helpPrompts.ts');

/** The catalog mirror, read as text: this script must not need the TypeScript compiled first. */
function catalogOrder() {
  const source = readFileSync(join(here, '..', 'src', 'prompts.ts'), 'utf8');
  const entries = [...source.matchAll(/\{\s*id:\s*'([^']+)',\s*role:\s*'([^']+)'[^}]*universal:\s*(true|false)/g)];
  if (entries.length === 0) {
    throw new Error('prompts.ts parsed to nothing — the PROMPTS entry shape must have changed');
  }
  return entries.map(([, id, role, universal]) => ({ id, role, universal: universal === 'true' }));
}

const ROLE_LABELS = {
  PlanCritique: 'Plan review',
  Architecture: 'Architecture',
  SecurityReliability: 'Security & reliability',
  UxDxPerformance: 'Performance & UX-DX',
};

const catalog = catalogOrder();
const shipped = readdirSync(promptsDir)
  .filter((f) => f.endsWith('.md'))
  .map((f) => f.replace(/\.md$/, ''));

// Every group leads with its universal prompt: the lens is the deliberate pick, so printing one
// first would read as the default.
const groups = [];
for (const [role, label] of Object.entries(ROLE_LABELS)) {
  const ids = catalog
    .filter((c) => c.role === role && c.id !== 'conventions')
    .sort((a, b) => Number(b.universal) - Number(a.universal))
    .map((c) => c.id);
  groups.push({ role: label, ids });
  if (role === 'PlanCritique') {
    groups.push({ role: 'Conventions (all three code roles, round 1)', ids: ['conventions'] });
  }
}

const ordered = groups.flatMap((g) => g.ids);
const missing = shipped.filter((id) => !ordered.includes(id));
const absent = ordered.filter((id) => !shipped.includes(id));
if (missing.length > 0 || absent.length > 0) {
  throw new Error(
    `the catalog and the prompts folder disagree — not in prompts.ts: [${missing}]; no .md file: [${absent}]`,
  );
}

const texts = ordered
  .map((id) => {
    const body = readFileSync(join(promptsDir, `${id}.md`), 'utf8').replace(/\r\n/g, '\n');
    return `  ${JSON.stringify(id)}: ${JSON.stringify(body)},`;
  })
  .join('\n');

const file = `/**
 * The full text of every prompt this product sends to a reviewer.
 *
 * <p>GENERATED by \`scripts/generate-help-prompts.mjs\` from \`src_mcp/src/prompts/*.md\`. Do not
 * edit by hand: \`helpPrompts.test.ts\` compares every entry here against those files, so an
 * edited prompt fails the build until this is regenerated. The alternative — reading the files at
 * runtime — cannot work, because the prompts are embedded in the server binary and the panel is
 * drawn before any server has started.</p>
 *
 * <p>Ordered as the catalog orders them: each role's universal prompt first, then its lenses.</p>
 */

export const PROMPT_TEXTS: Readonly<Record<string, string>> = {
${texts}
};

/**
 * How the page groups them. The conventions pass stands on its own: it is not a lens on one role's
 * question, it is a different question that all three code roles ask in round 1.
 */
export const PROMPT_GROUPS: readonly { readonly role: string; readonly ids: readonly string[] }[] = [
${groups.map((g) => `  { role: ${JSON.stringify(g.role)}, ids: [${g.ids.map((i) => `'${i}'`).join(', ')}] },`).join('\n')}
];
`;

writeFileSync(out, file, 'utf8');
console.log(`helpPrompts.ts: ${ordered.length} prompts in ${groups.length} groups`);
